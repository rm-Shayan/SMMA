"use client";

import React, { useState } from "react";
import { PageHeader } from "@/components/shared/PageHeader";
import {
  MOCK_APPROVAL_ITEMS,
  type ApprovalItem,
} from "@/mocks/approvalsData";
import {
  useGetApprovalsQuery,
  useDecideApprovalMutation,
  BackendApproval,
} from "@/redux/api/approvalsApi";
import { useWebSocketTopic } from "@/hooks/useWebSocketTopic";

function mapBackendApprovalToItem(a: BackendApproval): ApprovalItem {
  const input = a.input || {};
  const output = a.output || {};
  const content =
    (output.text as string) ||
    (input.prompt as string) ||
    (output.content as string) ||
    "Automated draft generated by agent, awaiting supervisor verification.";

  return {
    id: a.id,
    submitterName: a.agent_name || "Autonomous Agent",
    submitterInitials: (a.agent_name || "AG").slice(0, 2).toUpperCase(),
    companyName: "Styre Network",
    channel: "linkedin",
    channelLabel: "Agent Draft",
    agentNumber: 8,
    agentName: a.agent_name || "Publisher Agent",
    timeAgo: "Recently",
    priority: "urgent",
    previewSnippet: content.slice(0, 110) + "...",
    fullContent: content,
    destinationAccount: "Connected Organization Channel",
    hashtags: ["#Automation", "#StyreBot", "#AIAgents"],
    characterCount: content.length,
    maxCharacters: 3000,
    aiSafetyScore: 99.4,
  };
}
import {
  Search,
  CheckCircle2,
  XCircle,
  Edit3,
  Clock,
  Sparkles,
  ShieldCheck,
} from "lucide-react";
import toast from "react-hot-toast";

export default function ApprovalsPage() {
  const [selectedId, setSelectedId] = useState<string>(MOCK_APPROVAL_ITEMS[0]?.id || "");
  const [searchQuery, setSearchQuery] = useState("");
  const [dismissedIds, setDismissedIds] = useState<string[]>([]);
  const [typeFilter, setTypeFilter] = useState<"ALL" | "POSTS" | "EMAILS">("ALL");

  // Live RTK Query connection
  const { data: approvalsData, refetch } = useGetApprovalsQuery();
  const [decideApproval] = useDecideApprovalMutation();

  // Live WebSocket stream for incoming approvals from autonomous agents
  useWebSocketTopic<{ event_type?: string }>("notifications", () => {
    void refetch();
  });

  const items: ApprovalItem[] = React.useMemo(() => {
    const base =
      approvalsData?.approvals && approvalsData.approvals.length > 0
        ? approvalsData.approvals.map(mapBackendApprovalToItem)
        : MOCK_APPROVAL_ITEMS;
    return base.filter((i) => !dismissedIds.includes(i.id));
  }, [approvalsData, dismissedIds]);

  const selectedItem = items.find((i) => i.id === selectedId) || items[0];

  const filteredItems = items.filter((i) => {
    const matchesSearch =
      i.submitterName.toLowerCase().includes(searchQuery.toLowerCase()) ||
      i.previewSnippet.toLowerCase().includes(searchQuery.toLowerCase());
    if (!matchesSearch) return false;
    if (typeFilter === "POSTS") return i.channel === "linkedin" || i.channel === "instagram";
    if (typeFilter === "EMAILS") return i.channel === "email";
    return true;
  });

  const handleApprove = async (id: string) => {
    try {
      await decideApproval({ approvalId: id, status: "approved" }).unwrap();
      toast.success("Draft approved and scheduled for broadcast!");
    } catch (e: unknown) {
      const err = e as { data?: { message?: string } };
      toast.error(err?.data?.message || "Failed to approve draft");
      return;
    }
    const remaining = items.filter((i) => i.id !== id);
    if (selectedId === id && remaining.length > 0) {
      setSelectedId(remaining[0].id);
    }
  };

  const handleReject = async (id: string) => {
    try {
      await decideApproval({ approvalId: id, status: "rejected" }).unwrap();
      toast.error("Draft rejected and archived.");
    } catch (e: unknown) {
      const err = e as { data?: { message?: string } };
      toast.error(err?.data?.message || "Failed to reject draft");
      return;
    }
    const remaining = items.filter((i) => i.id !== id);
    if (selectedId === id && remaining.length > 0) {
      setSelectedId(remaining[0].id);
    }
  };

  const handleRequestChanges = (id: string) => {
    const note = prompt("Enter revision instructions for the AI agent / author:");
    if (note) {
      toast.success("Revision request sent back to author queue.");
      setDismissedIds((prev) => [...prev, id]);
    }
  };

  return (
    <div className="flex flex-col w-full max-w-[1560px] mx-auto pb-8">
      {/* Top Header Bar */}
      <PageHeader
        title="Approvals"
        badge={
          <span className="text-xs font-bold px-2.5 py-0.5 rounded-full bg-primary text-on-primary shadow-2xs tabular-nums">
            {items.length} pending
          </span>
        }
        description="Review drafts before they are sent. Human-in-the-loop safety gating for agent execution."
        actions={
          <div className="flex items-center gap-2">
            <div className="flex items-center bg-surface-container-low p-1 rounded-lg text-xs border border-outline-variant/30">
              <button
                type="button"
                onClick={() => setTypeFilter("ALL")}
                className={`px-2.5 py-1 rounded font-semibold transition-all ${typeFilter === "ALL"
                    ? "bg-surface-container-lowest text-on-surface shadow-2xs font-bold"
                    : "text-secondary hover:text-on-surface"
                  }`}
              >
                All types
              </button>
              <button
                type="button"
                onClick={() => setTypeFilter("POSTS")}
                className={`px-2.5 py-1 rounded font-semibold transition-all ${typeFilter === "POSTS"
                    ? "bg-surface-container-lowest text-on-surface shadow-2xs font-bold"
                    : "text-secondary hover:text-on-surface"
                  }`}
              >
                Social Posts
              </button>
              <button
                type="button"
                onClick={() => setTypeFilter("EMAILS")}
                className={`px-2.5 py-1 rounded font-semibold transition-all ${typeFilter === "EMAILS"
                    ? "bg-surface-container-lowest text-on-surface shadow-2xs font-bold"
                    : "text-secondary hover:text-on-surface"
                  }`}
              >
                Emails
              </button>
            </div>
          </div>
        }
      />

      {/* Main Split Architecture */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 items-start">
        {/* Left Column: Pending Queue (4 of 12 cols) */}
        <div className="lg:col-span-5 xl:col-span-4 flex flex-col gap-3">
          {/* Search Filter */}
          <div className="p-2.5 bg-surface-container-lowest rounded-xl border border-outline-variant/40 shadow-2xs flex items-center gap-2">
            <Search className="w-4 h-4 text-secondary ml-1" />
            <input
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder="Filter queue by author or text..."
              className="w-full bg-transparent text-xs text-on-surface placeholder:text-secondary focus:outline-none"
            />
            <span className="text-[10px] font-bold uppercase tracking-wider text-secondary px-2 py-0.5 rounded bg-surface-container-high shrink-0">
              Queue #{items.length}
            </span>
          </div>

          {/* Queue List Cards */}
          <div className="space-y-2.5">
            {filteredItems.map((item) => {
              const isSelected = selectedItem?.id === item.id;
              return (
                <div
                  key={item.id}
                  onClick={() => setSelectedId(item.id)}
                  className={`relative p-3.5 rounded-xl bg-surface-container-lowest border transition-all cursor-pointer shadow-2xs ${isSelected
                      ? "border-primary ring-2 ring-primary/20 bg-primary/5"
                      : "border-outline-variant/40 hover:border-outline-variant hover:shadow-xs"
                    }`}
                >
                  <div className="flex items-start justify-between gap-2">
                    <div className="flex items-center gap-2.5">
                      <div className="w-8 h-8 rounded-full bg-primary/10 text-primary font-bold text-xs flex items-center justify-center shrink-0">
                        {item.submitterInitials}
                      </div>
                      <div className="min-w-0">
                        <div className="text-xs font-bold text-on-surface truncate">
                          {item.submitterName}
                        </div>
                        <div className="text-[10px] text-secondary truncate">
                          {item.companyName}
                        </div>
                      </div>
                    </div>

                    <span
                      className={`text-[10px] font-bold px-2 py-0.5 rounded-full uppercase tracking-wider shrink-0 ${item.priority === "urgent"
                          ? "bg-red-100 text-red-800 "
                          : "bg-surface-container-high text-secondary"
                        }`}
                    >
                      {item.channelLabel}
                    </span>
                  </div>

                  <p className="text-xs text-secondary mt-2 line-clamp-2 leading-relaxed">
                    {item.previewSnippet}
                  </p>

                  <div className="flex items-center justify-between mt-3 pt-2 border-t border-outline-variant/30 text-[10px] text-secondary">
                    <span className="font-semibold text-primary flex items-center gap-1">
                      <Sparkles className="w-3 h-3" /> #{item.agentNumber} {item.agentName.split(" ")[0]}
                    </span>
                    <span className="flex items-center gap-1">
                      <Clock className="w-3 h-3" /> {item.timeAgo}
                    </span>
                  </div>
                </div>
              );
            })}

            {filteredItems.length === 0 && (
              <div className="p-8 text-center text-xs text-secondary bg-surface-container-lowest rounded-xl border border-outline-variant/30">
                <CheckCircle2 className="w-8 h-8 text-emerald-500 mx-auto mb-2" />
                No pending approvals in this view!
              </div>
            )}
          </div>
        </div>

        {/* Right Column: Detailed Review Panel (8 of 12 cols) */}
        {selectedItem ? (
          <div className="lg:col-span-7 xl:col-span-8 flex flex-col gap-4">
            {/* Header Details Card */}
            <div className="p-5 rounded-2xl bg-surface-container-lowest border border-outline-variant/40 shadow-2xs flex flex-col sm:flex-row sm:items-center justify-between gap-4">
              <div className="flex items-center gap-3">
                <div className="w-11 h-11 rounded-xl bg-primary/10 text-primary flex items-center justify-center text-base font-bold shrink-0">
                  {selectedItem.submitterInitials}
                </div>
                <div>
                  <div className="flex items-center gap-2 flex-wrap">
                    <span className="text-sm font-bold text-on-surface">
                      {selectedItem.submitterName}
                    </span>
                    <span className="text-[10px] font-bold px-2 py-0.5 rounded-full bg-primary text-on-primary">
                      Agent #{selectedItem.agentNumber} {selectedItem.agentName}
                    </span>
                  </div>
                  <p className="text-xs text-secondary mt-0.5">
                    Submitted {selectedItem.timeAgo} • via Workspace Engine
                  </p>
                </div>
              </div>

              <div className="flex items-center gap-2">
                <span className="px-2.5 py-1 rounded-full bg-red-100 text-red-800 text-[11px] font-bold">
                  Priority: {selectedItem.priority === "urgent" ? "Urgent" : "Standard"}
                </span>
              </div>
            </div>

            {/* Destination Target */}
            <div className="px-4 py-3 rounded-xl bg-surface-container-lowest border border-outline-variant/40 shadow-2xs flex items-center justify-between text-xs">
              <div>
                <span className="text-[10px] font-bold uppercase tracking-wider text-secondary block">
                  Destination Target
                </span>
                <span className="font-semibold text-on-surface mt-0.5 block">
                  {selectedItem.destinationAccount}
                </span>
              </div>
              <span className="text-[10px] font-bold px-2 py-1 rounded bg-emerald-100 text-emerald-800 flex items-center gap-1">
                <ShieldCheck className="w-3.5 h-3.5" /> Token Active
              </span>
            </div>

            {/* High-Fidelity Draft Preview */}
            <div className="p-5 rounded-2xl bg-surface-container-lowest border border-outline-variant/40 shadow-2xs flex flex-col gap-4">
              <div className="flex items-center justify-between pb-3 border-b border-outline-variant/30 text-xs">
                <span className="font-bold text-on-surface">Live Draft Simulation</span>
                <span className="text-secondary font-medium">Desktop &amp; Mobile View</span>
              </div>

              {/* Simulated Social Card */}
              <div className="p-4 rounded-xl bg-surface-container-low/60 border border-outline-variant/30 space-y-3">
                <div className="flex items-center gap-2.5">
                  <div className="w-9 h-9 rounded-full bg-primary text-on-primary font-bold text-xs flex items-center justify-center">
                    AG
                  </div>
                  <div>
                    <div className="text-xs font-bold text-on-surface">Apex Growth Partners</div>
                    <div className="text-[10px] text-secondary">42,500 followers • Just now</div>
                  </div>
                </div>

                <div className="p-3 bg-surface-container-lowest rounded-lg text-xs text-on-surface leading-relaxed whitespace-pre-line border border-outline-variant/30">
                  {selectedItem.fullContent}
                </div>

                {selectedItem.mediaUrl && (
                  <div className="rounded-lg overflow-hidden border border-outline-variant/30 bg-surface-container-lowest">
                    <div className="relative h-52 w-full overflow-hidden bg-inverse-surface">
                      {/* eslint-disable-next-line @next/next/no-img-element */}
                      <img
                        src={selectedItem.mediaUrl}
                        alt={selectedItem.mediaName || "Media Preview"}
                        className="w-full h-full object-cover"
                      />
                    </div>
                    <div className="p-2.5 flex items-center justify-between text-xs text-secondary">
                      <span className="truncate">{selectedItem.mediaName}</span>
                      <span className="text-[11px]">{selectedItem.mediaSize}</span>
                    </div>
                  </div>
                )}

                {selectedItem.hashtags.length > 0 && (
                  <div className="flex items-center gap-1.5 flex-wrap pt-1">
                    {selectedItem.hashtags.map((tag) => (
                      <span
                        key={tag}
                        className="text-[10px] font-bold px-2 py-0.5 rounded bg-primary/10 text-primary"
                      >
                        {tag}
                      </span>
                    ))}
                  </div>
                )}
              </div>

              {/* AI Safety Check */}
              <div className="p-3.5 rounded-xl bg-emerald-50/60 border border-emerald-200 flex items-center justify-between text-xs">
                <div className="flex items-center gap-2.5">
                  <ShieldCheck className="w-5 h-5 text-emerald-600" />
                  <div>
                    <span className="font-bold text-emerald-900 block">
                      AI Safety &amp; Guardrails Engine: Pass
                    </span>
                    <span className="text-[11px] text-emerald-700 ">
                      Brand voice confidence score: {selectedItem.aiSafetyScore}% • 0 hallucinations detected
                    </span>
                  </div>
                </div>
                <span className="font-bold text-emerald-800 text-xs">99.4% Match</span>
              </div>

              {/* Action Buttons Footer */}
              <div className="pt-3 border-t border-outline-variant/30 flex items-center justify-between flex-wrap gap-2">
                <button
                  type="button"
                  onClick={() => handleReject(selectedItem.id)}
                  className="px-3.5 py-2 rounded-lg text-red-600 hover:bg-red-50 text-xs font-semibold transition-colors flex items-center gap-1.5"
                >
                  <XCircle className="w-4 h-4" /> Reject Draft
                </button>

                <div className="flex items-center gap-2">
                  <button
                    type="button"
                    onClick={() => handleRequestChanges(selectedItem.id)}
                    className="px-3.5 py-2 rounded-lg border border-outline-variant/60 bg-surface-container-lowest hover:bg-surface-container-low text-on-surface text-xs font-semibold transition-colors flex items-center gap-1.5"
                  >
                    <Edit3 className="w-3.5 h-3.5" /> Request changes
                  </button>

                  <button
                    type="button"
                    onClick={() => handleApprove(selectedItem.id)}
                    className="px-4 py-2 rounded-lg bg-primary hover:bg-primary-hover text-on-primary text-xs font-semibold shadow-xs transition-colors flex items-center gap-1.5"
                  >
                    <CheckCircle2 className="w-4 h-4" /> Approve &amp; Schedule
                  </button>
                </div>
              </div>
            </div>
          </div>
        ) : null}
      </div>
    </div>
  );
}
